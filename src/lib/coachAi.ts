import type Anthropic from '@anthropic-ai/sdk';
import type { AppState, CoachMessage } from '../types';
import { trainingSummary } from './coach';

const KEY_STORAGE = 'coach-anthropic-api-key';
export const COACH_MODEL = 'claude-opus-5-5';

// The key lives in this browser only and is never included in backups.
export function getApiKey(): string {
  try {
    return localStorage.getItem(KEY_STORAGE) ?? '';
  } catch {
    return '';
  }
}

export function setApiKey(key: string): void {
  try {
    if (key) localStorage.setItem(KEY_STORAGE, key.trim());
    else localStorage.removeItem(KEY_STORAGE);
  } catch {
    /* storage unavailable */
  }
}

const SYSTEM_PROMPT = `You are an experienced strength coach for powerlifters and barbell athletes (think Barbell Medicine / RTS / Starting Strength-literate). You coach through a mobile training-log app. The user's training data is provided below in <training_data>; it is generated by the app and is accurate.

How you coach:
- Base every claim on the data. Quote specific numbers (e1RM, RPE, weeks since PR, sets/week) when you diagnose something.
- When a lift is stalled or regressing, work out WHY before prescribing. If the data can't tell you, ask focused diagnostic questions first: where in the range the lift slows or fails (e.g. off the chest / mid-range / lockout; out of the hole; off the floor / at the knee / lockout), what technique breaks down, how heavy reps feel (grind vs. fast-then-stop), and recovery (sleep, diet phase, stress, injuries). Ask at most 2-3 questions per message, numbered, so they are easy to answer on a phone.
- Once you know enough, give a concrete plan: specific variations with sets × reps @ RPE, how many weeks, where they go in the week, what to change in volume/intensity/frequency, and 1-3 technique cues. Prefer changing one or two things at a time.
- Goals and nutrition: the data includes the lifter's goals with computed feasibility (required vs realistic weekly progress, projections) and a calorie/macro plan. Use those numbers. Say plainly when a goal is not feasible by its date, explain why (training level, diet phase, time left), and propose an adapted target or date. If cutting and gaining strength conflict, recommend how to sequence them. Ask about adherence (how consistently they hit calories and protein, sleep) before blaming the program.
- Use RPE-based autoregulation language. Loads in kg. If you suggest loads, derive them from the e1RMs in the data.
- Be honest about uncertainty. Don't diagnose injuries; for pain, recommend reducing load and seeing a qualified professional if it persists.
- Style: direct, encouraging, no fluff. Short paragraphs and bullet points; this is read on a phone between sets. Keep most replies under ~250 words unless the user asks for a full program.`;

function friendlyError(e: unknown, A: typeof Anthropic): string {
  if (e instanceof A.AuthenticationError) return 'The API key was rejected. Check it in Coach → AI settings.';
  if (e instanceof A.PermissionDeniedError) return 'This API key does not have access to the model.';
  if (e instanceof A.RateLimitError) return 'Rate limited by the API. Wait a moment and try again.';
  if (e instanceof A.BadRequestError) return `The request was rejected: ${e.message}`;
  if (e instanceof A.APIConnectionError) return 'Could not reach the Claude API. Check your internet connection.';
  if (e instanceof A.APIError) return `Claude API error ${e.status ?? ''}: ${e.message}`;
  return e instanceof Error ? e.message : String(e);
}

/**
 * Streams the coach's reply to the conversation. Calls onText with the accumulated
 * text as it arrives and resolves with the final text.
 */
export async function askCoach(state: AppState, chat: CoachMessage[], onText: (text: string) => void, signal?: AbortSignal): Promise<string> {
  const apiKey = getApiKey();
  if (!apiKey) throw new Error('Add your Anthropic API key in Coach → AI settings first.');
  // Loaded on demand so the SDK isn't in the initial bundle.
  const { default: A } = await import('@anthropic-ai/sdk');
  // Calls go straight from this device to the Claude API using the user's own key.
  const client = new A({ apiKey, dangerouslyAllowBrowser: true });

  const messages: Anthropic.Beta.BetaMessageParam[] = chat.filter((m) => !m.error && m.text.trim()).map((m) => ({ role: m.role, content: m.text }));
  // Conversation must start with the user.
  while (messages.length && messages[0].role !== 'user') messages.shift();

  try {
    const stream = client.beta.messages.stream(
      {
        model: COACH_MODEL,
        max_tokens: 16000,
        output_config: { effort: 'high' },
        // Server-side refusal fallback: a declined request is retried on a suitable model.
        betas: ['server-side-fallback-2026-07-01'],
        fallbacks: 'default',
        system: [
          { type: 'text', text: SYSTEM_PROMPT, cache_control: { type: 'ephemeral' } },
          { type: 'text', text: `<training_data>\nToday: ${new Date().toISOString().slice(0, 10)}\n${trainingSummary(state)}\n</training_data>` },
        ],
        messages,
      },
      { signal },
    );
    let text = '';
    stream.on('text', (delta) => {
      text += delta;
      onText(text);
    });
    const final = await stream.finalMessage();
    if (final.stop_reason === 'refusal') throw new Error('The coach declined to answer that. Try rephrasing your question.');
    return text;
  } catch (e) {
    if (e instanceof A.APIUserAbortError) throw e;
    throw new Error(friendlyError(e, A));
  }
}
