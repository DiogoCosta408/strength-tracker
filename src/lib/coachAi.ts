import type { AppState, CoachMessage } from '../types';
import { trainingSummary } from './coach';

const KEY_STORAGE = 'coach-google-api-key';
const MODEL_STORAGE = 'coach-google-model';
const API = 'https://generativelanguage.googleapis.com/v1beta';

/**
 * Preferred models, best first. Google renames and retires these fairly often, so the model
 * is resolved against what the key can actually see (see resolveModel) rather than pinned —
 * a stale id here degrades to "pick a current flash model" instead of a hard failure.
 */
const PREFERRED_MODELS = ['gemini-3.5-flash-lite', 'gemini-3.8-flash', 'gemini-2.5-flash', 'gemini-2.0-flash'];

/** Models that exist but can't hold a coaching conversation. */
const NOT_CHAT = /embedding|aqa|vision|image|imagen|tts|audio|live|transcribe|veo|banana/i;

// The key lives in this browser only and is never included in backups or cloud sync.
export function getApiKey(): string {
  try {
    return localStorage.getItem(KEY_STORAGE) ?? '';
  } catch {
    return '';
  }
}

export function setApiKey(key: string): void {
  try {
    if (key) localStorage.setItem(KEY_STORAGE, key.trim());
    else {
      localStorage.removeItem(KEY_STORAGE);
      localStorage.removeItem(MODEL_STORAGE); // a different key may see different models
    }
  } catch {
    /* storage unavailable */
  }
}

/** Which model this key will be used with, resolved once from the key's own model list and cached. */
export async function resolveModel(apiKey: string, signal?: AbortSignal): Promise<string> {
  try {
    const cached = localStorage.getItem(MODEL_STORAGE);
    if (cached) return cached;
  } catch {
    /* storage unavailable — resolve every time */
  }
  let available: string[] = [];
  try {
    const res = await fetch(`${API}/models?key=${encodeURIComponent(apiKey)}`, { signal });
    if (res.ok) {
      const data = (await res.json()) as { models?: { name?: string; supportedGenerationMethods?: string[] }[] };
      available = (data.models ?? [])
        .filter((m) => m.supportedGenerationMethods?.includes('generateContent'))
        .map((m) => (m.name ?? '').replace(/^models\//, ''))
        .filter((n) => n && !NOT_CHAT.test(n));
    }
  } catch {
    /* offline or blocked — fall back to the first preferred id below */
  }
  const picked =
    PREFERRED_MODELS.find((p) => available.includes(p)) ??
    available.find((n) => /flash/i.test(n)) ??
    available[0] ??
    PREFERRED_MODELS[0];
  try {
    localStorage.setItem(MODEL_STORAGE, picked);
  } catch {
    /* ignore */
  }
  return picked;
}

const SYSTEM_PROMPT = `You are an experienced strength coach for powerlifters and barbell athletes (think Barbell Medicine / RTS / Starting Strength-literate). You coach through a mobile training-log app. The user's training data is provided below in <training_data>; it is generated by the app and is accurate.

How you coach:
- Base every claim on the data. Quote specific numbers (e1RM, RPE, weeks since PR, sets/week) when you diagnose something.
- When a lift is stalled or regressing, work out WHY before prescribing. If the data can't tell you, ask focused diagnostic questions first: where in the range the lift slows or fails (e.g. off the chest / mid-range / lockout; out of the hole; off the floor / at the knee / lockout), what technique breaks down, how heavy reps feel (grind vs. fast-then-stop), and recovery (sleep, diet phase, stress, injuries). Ask at most 2-3 questions per message, numbered, so they are easy to answer on a phone.
- Once you know enough, give a concrete plan: specific variations with sets × reps @ RPE, how many weeks, where they go in the week, what to change in volume/intensity/frequency, and 1-3 technique cues. Prefer changing one or two things at a time.
- Goals and nutrition: the data includes the lifter's goals with computed feasibility (required vs realistic weekly progress, projections) and a calorie/macro plan. Use those numbers. Say plainly when a goal is not feasible by its date, explain why (training level, diet phase, time left), and propose an adapted target or date. If cutting and gaining strength conflict, recommend how to sequence them. Ask about adherence (how consistently they hit calories and protein, sleep) before blaming the program.
- Use RPE-based autoregulation language. Loads in kg. If you suggest loads, derive them from the e1RMs in the data.
- Be honest about uncertainty. Don't diagnose injuries; for pain, recommend reducing load and seeing a qualified professional if it persists.
- Style: direct, encouraging, no fluff. Short paragraphs and bullet points; this is read on a phone between sets. Keep most replies under ~250 words unless the user asks for a full program.`;

function friendlyError(status: number, body: string): string {
  const detail = (() => {
    try {
      return (JSON.parse(body) as { error?: { message?: string } }).error?.message ?? '';
    } catch {
      return '';
    }
  })();
  if (status === 400 && /API key not valid/i.test(detail)) return 'That API key was rejected. Check it in Coach → AI settings.';
  // Google's own text says which of these it is (key invalid, API not enabled for the
  // project, referrer-restricted key…), so pass it through rather than guessing.
  if (status === 401 || status === 403) return detail ? `Google rejected the key: ${detail}` : 'The API key was rejected or lacks access. Check it in Coach → AI settings.';
  if (status === 404) return detail ? `Model unavailable: ${detail}` : 'That model is not available to this key. Remove and re-enter the key to pick another.';
  if (status === 429) return 'Rate limited by the free tier. Wait a moment and try again.';
  if (status >= 500) return 'Google AI is having trouble right now. Try again shortly.';
  return detail ? `Gemini API error ${status}: ${detail}` : `Gemini API error ${status}`;
}

/**
 * Streams the coach's reply. Calls onText with the accumulated text as it arrives and
 * resolves with the final text. Requests go straight from this device to the Gemini API
 * using the user's own key.
 */
export async function askCoach(state: AppState, chat: CoachMessage[], onText: (text: string) => void, signal?: AbortSignal): Promise<string> {
  const apiKey = getApiKey();
  if (!apiKey) throw new Error('Add your Google AI Studio API key in Coach → AI settings first.');
  const model = await resolveModel(apiKey, signal);

  const contents = chat
    .filter((m) => !m.error && m.text.trim())
    .map((m) => ({ role: m.role === 'assistant' ? 'model' : 'user', parts: [{ text: m.text }] }));
  // The conversation must start with the user.
  while (contents.length && contents[0].role !== 'user') contents.shift();

  const res = await fetch(`${API}/models/${encodeURIComponent(model)}:streamGenerateContent?alt=sse&key=${encodeURIComponent(apiKey)}`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    signal,
    body: JSON.stringify({
      systemInstruction: {
        parts: [{ text: `${SYSTEM_PROMPT}\n\n<training_data>\nToday: ${new Date().toISOString().slice(0, 10)}\n${trainingSummary(state)}\n</training_data>` }],
      },
      contents,
      generationConfig: { temperature: 0.7, maxOutputTokens: 4096 },
    }),
  });
  if (!res.ok || !res.body) throw new Error(friendlyError(res.status, await res.text().catch(() => '')));

  const reader = res.body.getReader();
  const decoder = new TextDecoder();
  let buffer = '';
  let text = '';
  let blocked = '';

  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    buffer += decoder.decode(value, { stream: true });
    const lines = buffer.split('\n');
    buffer = lines.pop() ?? ''; // keep the partial line for the next chunk
    for (const line of lines) {
      const trimmed = line.trim();
      if (!trimmed.startsWith('data:')) continue;
      const payload = trimmed.slice(5).trim();
      if (!payload || payload === '[DONE]') continue;
      try {
        const json = JSON.parse(payload) as {
          candidates?: { content?: { parts?: { text?: string }[] }; finishReason?: string }[];
          promptFeedback?: { blockReason?: string };
        };
        if (json.promptFeedback?.blockReason) blocked = json.promptFeedback.blockReason;
        const candidate = json.candidates?.[0];
        for (const part of candidate?.content?.parts ?? []) {
          if (typeof part.text === 'string' && part.text) {
            text += part.text;
            onText(text);
          }
        }
        const reason = candidate?.finishReason;
        if (reason && reason !== 'STOP' && reason !== 'MAX_TOKENS') blocked = reason;
      } catch {
        /* a partial or non-JSON keep-alive line — ignore */
      }
    }
  }

  if (!text) {
    if (blocked === 'SAFETY' || blocked === 'PROHIBITED_CONTENT') throw new Error('The coach declined to answer that. Try rephrasing your question.');
    throw new Error(blocked ? `The coach stopped early (${blocked}). Try rephrasing your question.` : 'No reply came back. Try again.');
  }
  return text;
}
